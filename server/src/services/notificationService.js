const nodemailer = require('nodemailer');
const Notification = require('../models/Notification');

let transporter = null;

const initTransporter = async () => {
  if (transporter) return transporter;

  if (process.env.SMTP_HOST && process.env.SMTP_USER) {
    transporter = nodemailer.createTransport({
      host: process.env.SMTP_HOST,
      port: process.env.SMTP_PORT || 587,
      secure: process.env.SMTP_SECURE === 'true',
      auth: {
        user: process.env.SMTP_USER,
        pass: process.env.SMTP_PASS,
      },
    });
    console.log('[Notification Service] Configured custom SMTP transporter');
  } else {
    // Development fallback using Ethereal test account or simulated transport
    try {
      const testAccount = await nodemailer.createTestAccount();
      transporter = nodemailer.createTransport({
        host: 'smtp.ethereal.email',
        port: 587,
        secure: false,
        auth: {
          user: testAccount.user,
          pass: testAccount.pass,
        },
      });
      console.log(`[Notification Service] Ethereal dev mailbox ready: ${testAccount.user}`);
    } catch (err) {
      console.warn('[Notification Service] Using console fallback for email notifications');
      transporter = {
        sendMail: async (opts) => {
          console.log(`[SIMULATED EMAIL] To: ${opts.to} | Subject: ${opts.subject}`);
          return { messageId: 'simulated-' + Date.now() };
        },
      };
    }
  }

  return transporter;
};

/**
 * Send notification to a user (in-app and email)
 */
const sendNotification = async ({
  recipientId,
  recipientEmail,
  recipientName,
  bloodRequestId = null,
  title,
  message,
  type,
  channel = 'both',
}) => {
  let deliveryStatus = 'delivered';
  let emailSentTo = recipientEmail || '';

  // 1. Create in-app notification in DB
  let notificationDoc;
  try {
    notificationDoc = await Notification.create({
      recipient: recipientId,
      bloodRequest: bloodRequestId,
      title,
      message,
      type,
      channel,
      deliveryStatus: 'pending',
      emailSentTo,
    });
  } catch (dbErr) {
    console.error('[Notification DB Error]', dbErr.message);
  }

  // 2. Dispatch email if channel is email or both
  if (channel === 'email' || channel === 'both') {
    if (recipientEmail) {
      try {
        const mailer = await initTransporter();
        const info = await mailer.sendMail({
          from: `"Blood Emergency Network" <${process.env.EMAIL_FROM || 'emergency@bloodnetwork.org'}>`,
          to: recipientEmail,
          subject: `[EMERGENCY NOTIFICATION] ${title}`,
          html: `
            <div style="font-family: Arial, sans-serif; max-width: 600px; margin: 0 auto; padding: 20px; border: 1px solid #fee2e2; border-radius: 8px; background: #fff5f5;">
              <div style="background: #dc2626; color: white; padding: 12px 20px; border-radius: 6px; text-align: center;">
                <h2 style="margin: 0; font-size: 20px;">Blood Donation & Emergency Network</h2>
              </div>
              <div style="padding: 20px; color: #1f2937;">
                <h3 style="color: #991b1b; margin-top: 0;">${title}</h3>
                <p style="font-size: 15px; line-height: 1.6;">Hello ${recipientName || 'Donor'},</p>
                <p style="font-size: 15px; line-height: 1.6; background: #ffffff; padding: 16px; border-radius: 6px; border-left: 4px solid #dc2626;">
                  ${message}
                </p>
                <p style="font-size: 13px; color: #6b7280; margin-top: 25px;">
                  This is an urgent communication generated by the Emergency Blood Donation System.
                  Please respond promptly if you are available and medically eligible to donate.
                </p>
              </div>
            </div>
          `,
        });

        if (nodemailer.getTestMessageUrl && info) {
          const previewUrl = nodemailer.getTestMessageUrl(info);
          if (previewUrl) {
            console.log(`[Notification Service] Ethereal Email Preview: ${previewUrl}`);
          }
        }

        if (notificationDoc) {
          notificationDoc.deliveryStatus = 'delivered';
          await notificationDoc.save();
        }
      } catch (emailErr) {
        console.error('[Email Dispatch Error]', emailErr.message);
        if (notificationDoc) {
          notificationDoc.deliveryStatus = 'failed';
          await notificationDoc.save();
        }
      }
    }
  }

  return notificationDoc;
};

module.exports = {
  sendNotification,
  initTransporter,
};
